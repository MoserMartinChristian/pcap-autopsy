#!/usr/bin/env node
// Compares packet count, TCP connections, retransmissions, duplicate ACKs, zero windows and
// out-of-order segments of every synthetic capture with tshark. Writes docs/tshark-comparison.md.
// Usage: node scripts/compare-tshark.js   (needs tshark in PATH)
'use strict';
const fs = require('fs');
const os = require('os');
const path = require('path');
const { execFileSync } = require('child_process');
const PA = require('./load.js');
const M = PA.store.M;

function tshark(file, args) {
  return execFileSync('tshark', ['-n', '-r', file].concat(args), { encoding: 'utf8', maxBuffer: 1 << 28, stdio: ['ignore', 'pipe', 'ignore'] });
}
let version;
try { version = execFileSync('tshark', ['-v'], { encoding: 'utf8' }).split('\n')[0]; } catch (e) {
  console.error('tshark not found – comparison not possible.');
  process.exit(2);
}
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'pa-tshark-'));
const ids = PA.scenarios.list.map((s) => s.id).concat(PA.scenarios.variants);
const rows = [];
let diffs = 0;
for (const id of ids) {
  const { bytes } = PA.scenarios.build(id);
  const file = path.join(dir, id + '.pcap');
  fs.writeFileSync(file, bytes);
  const r = PA.pipeline.analyzeBytes(bytes);
  const S = r.store.S;
  const count = (bit) => { let n = 0; for (let i = 0; i < S.n; i++) if (S.marks[i] & bit) n++; return n; };
  const ours = {
    packets: S.n,
    tcp: S.flows.filter((f) => f.proto === 'tcp').length,
    retrans: count(M.RETRANS),
    dupack: count(M.DUPACK),
    zerowin: count(M.ZEROWIN),
    ooo: count(M.OOO),
  };
  const lines = (filter) => { const o = tshark(file, ['-Y', filter, '-T', 'fields', '-e', 'frame.number']).trim(); return o ? o.split('\n').length : 0; };
  const conv = tshark(file, ['-q', '-z', 'conv,tcp']).split('\n').filter((l) => /<->/.test(l)).length;
  const theirs = {
    packets: lines('frame'),
    tcp: conv,
    retrans: lines('tcp.analysis.retransmission'),
    dupack: lines('tcp.analysis.duplicate_ack'),
    zerowin: lines('tcp.analysis.zero_window'),
    ooo: lines('tcp.analysis.out_of_order'),
  };
  const notes = [];
  for (const k of Object.keys(ours)) if (ours[k] !== theirs[k]) { notes.push(k + ' ' + ours[k] + ' vs ' + theirs[k]); diffs++; }
  rows.push({ id, ours, theirs, notes });
  console.log(id.padEnd(22), notes.length ? 'DIFF ' + notes.join('; ') : 'match');
}
const fmt = (o, t) => (o === t ? String(o) : `**${o} / ${t}**`);
let md = '# Comparison with tshark\n\n';
md += `Generated by \`node scripts/compare-tshark.js\` with ${version}.\n\n`;
md += 'Each cell shows PCAP Autopsy’s count. Where tshark differs, the cell shows **ours / tshark**.\n\n';
md += '| Capture | Packets | TCP conns | Retransmissions | Dup ACKs | Zero window | Out-of-order |\n|---|---|---|---|---|---|---|\n';
for (const r of rows) md += `| ${r.id} | ${fmt(r.ours.packets, r.theirs.packets)} | ${fmt(r.ours.tcp, r.theirs.tcp)} | ${fmt(r.ours.retrans, r.theirs.retrans)} | ${fmt(r.ours.dupack, r.theirs.dupack)} | ${fmt(r.ours.zerowin, r.theirs.zerowin)} | ${fmt(r.ours.ooo, r.theirs.ooo)} |\n`;
md += `\n${diffs} differing cells.\n`;
fs.writeFileSync(path.join(__dirname, '..', 'docs', 'tshark-comparison.raw.md'), md);
fs.rmSync(dir, { recursive: true, force: true });
